  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_FACULTY_WITH_MULTIPLE_TAS" ("FACULTY_NAME", "TA_COUNT") AS 
  SELECT f.faculty_name, COUNT(*) AS ta_count
FROM faculty f
JOIN ta_assignment ta ON ta.faculty_id = f.faculty_id
WHERE ta.assignment_status = 'ACTIVE'
GROUP BY f.faculty_name
HAVING COUNT(*) > 1;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_HOURS_WORKED_PER_TA" ("TA_NAME", "TOTAL_HOURS") AS 
  SELECT s.first_name || ' ' || s.last_name AS ta_name,
       SUM(w.hours_worked) AS total_hours
FROM work_log w
JOIN ta_assignment ta ON ta.assignment_id = w.assignment_id
JOIN student s ON s.student_id = ta.student_id
GROUP BY s.first_name, s.last_name;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VW_TA_FACULTY_MAPPING" ("TA_NAME", "FACULTY_NAME", "COURSE_TITLE", "SECTION_NUMBER") AS 
  SELECT s.first_name || ' ' || s.last_name AS ta_name,
       f.faculty_name,
       c.course_title,
       sec.section_number
FROM ta_assignment ta
JOIN student s   ON s.student_id  = ta.student_id
JOIN faculty f   ON f.faculty_id  = ta.faculty_id
JOIN section sec ON sec.section_id = ta.section_id
JOIN course c    ON c.course_id   = sec.course_id
WHERE ta.assignment_status = 'ACTIVE';