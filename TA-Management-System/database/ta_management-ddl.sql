create or replace FUNCTION TA_APP_AUTH (
    p_username IN VARCHAR2,
    p_password IN VARCHAR2
)
RETURN BOOLEAN
IS
    l_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO l_count
      FROM TA_USERS
     WHERE UPPER(USERNAME) = UPPER(p_username)
       AND PASSWORD_HASH = UPPER(STANDARD_HASH(p_password, 'SHA256'))
       AND IS_ACTIVE = 'Y';

    RETURN l_count > 0;
END;
/
create or replace FUNCTION ta_authenticate ( p_username IN VARCHAR2, p_password IN VARCHAR2 ) RETURN BOOLEAN IS l_count NUMBER; BEGIN SELECT COUNT(*) INTO l_count FROM ta_users WHERE username = p_username AND password_hash = STANDARD_HASH(p_password, 'SHA256') AND is_active = 'Y'; RETURN (l_count > 0); END;
